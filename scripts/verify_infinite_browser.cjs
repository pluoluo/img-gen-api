// Browser acceptance uses fixture generation results; no paid model calls.
const { chromium } = require('../canvas/node_modules/playwright');
const {assertOfflineValidation}=require('./infinite_test_environment.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.INFINITE_TEST_URL || 'http://127.0.0.1:8770';
const output = 'data/infinite-validation';
const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==';
(async () => {
  fs.mkdirSync(output, { recursive: true });
  await assertOfflineValidation(base);
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const submissions = [];
    await page.route('**/api/v1/infinite/generate', async route => {
      submissions.push(route.request().postDataJSON());
      await route.fulfill({ json: { task_id: 'browser-fixture' } });
    });
    await page.route('**/api/v1/tasks/browser-fixture', route => route.fulfill({ json: { status: 'completed', progress: 100, images: [{ base64: png }] } }));
    await page.goto(`${base}/infinite/canvas`);
    await page.getByRole('button', { name: '新建画布', exact: true }).first().click();
    await page.waitForURL('**/infinite/canvas/*');
    const projectUrl = page.url();
    await page.getByRole('button', { name: '文本', exact: true }).click();
    await page.waitForTimeout(700); // upstream canvas store persists after 400 ms
    await page.reload();
    await page.getByRole('button', { name: '打开画布菜单', exact: true }).waitFor();
    assert(!((await page.locator('body').innerText()).includes('画布暂无节点')), 'text node must survive refresh');
    await page.screenshot({ path: `${output}/canvas-with-text.png` });
    await page.goto(`${base}/infinite/image`);
    await page.getByPlaceholder('描述画面主体、风格、构图、光线和用途').fill('Infinite acceptance image');
    await page.getByRole('button', { name: '开始生成', exact: true }).click();
    await page.getByRole('button', { name: '加入参考图', exact: true }).waitFor();
    assert.equal(submissions.length, 1);
    assert.equal(submissions[0].sub_model, 'gpt-image-2.5-flare');
    await page.getByRole('button', { name: '加入我的资产', exact: true }).click();
    await page.getByRole('button', { name: '加入参考图', exact: true }).click();
    await page.getByRole('button', { name: '开始生成', exact: true }).click();
    await page.waitForFunction(() => document.body.innerText.includes('图片已生成'));
    await page.getByRole('button', { name: '加入参考图', exact: true }).waitFor();
    assert.equal(submissions.length, 2);
    assert.deepEqual(submissions[1].image_base64s, [png]);
    await page.goto(`${base}/infinite/config`);
    await page.getByRole('tab', { name: 'WebDAV', exact: true }).click();
    const directory = `browser-acceptance-${Date.now()}`;
    await page.getByPlaceholder('infinite-canvas', { exact: true }).fill(directory);
    await page.getByRole('button', { name: '测试连接', exact: true }).click();
    await page.getByText('WebDAV 连接可用', { exact: true }).waitFor();
    await page.getByRole('button', { name: '立即同步', exact: true }).click();
    await page.getByText(/同步完成：1 个画布/).waitFor();
    await page.screenshot({ path: `${output}/server-sync.png`, fullPage: true });
    const manifest = await context.request.get(`${base}/api/v1/infinite/storage/${directory}/canvas/manifest.json`);
    assert.equal(manifest.status(), 200);
    const remote = await manifest.json();
    assert.equal(remote.data.projects[0].id, projectUrl.split('/').pop());
    assert.equal(remote.data.projects[0].nodes.length, 1);
    const clean = await browser.newContext();
    const restored = await clean.newPage();
    await restored.goto(`${base}/infinite/config`);
    await restored.getByRole('tab', { name: 'WebDAV', exact: true }).click();
    await restored.getByPlaceholder('infinite-canvas', { exact: true }).fill(directory);
    await restored.getByRole('button', { name: '立即同步', exact: true }).click();
    await restored.getByText(/同步完成：1 个画布/).waitFor({timeout:10000}).catch(async error => { console.error('RESTORE STATE', await restored.locator('body').innerText()); throw error; });
    await restored.goto(projectUrl);
    await restored.getByRole('button', { name: '打开画布菜单', exact: true }).waitFor();
    assert(!((await restored.locator('body').innerText()).includes('画布暂无节点')), 'server restore must bring back text node');
    await restored.goto(`${base}/infinite/assets`);
    await restored.getByText('生成结果 1', { exact: true }).first().waitFor();
    await restored.screenshot({ path: `${output}/restored-assets.png`, fullPage: true });
    assert.deepEqual(errors, []);
    const summary = { projectUrl, directory, generationSubmissions: submissions.length, browserErrors: errors, serverRestore: true, assetRestore: true };
    fs.writeFileSync(`${output}/browser-result.json`, JSON.stringify(summary, null, 2));
    console.log(JSON.stringify(summary));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });

// Category-scoped multi-tag filtering in the canvas sidebar; no model requests.
const { chromium } = require('../canvas/node_modules/playwright');
const { assertOfflineValidation } = require('./infinite_test_environment.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const origin = process.env.INFINITE_TEST_URL || 'http://127.0.0.1:8772';
const output = 'data/infinite-validation';
const sourceIds = ['prompt-portal', 'banana-prompt-quicker', 'davidwu-gpt-image2-prompts', 'freestylefly-gpt-image-2', 'awesome-gpt-image', 'awesome-gpt4o-image-prompts', 'youmind-gpt-image-2', 'youmind-nano-banana-pro'];
const titles = ['胶片人像摄影', '黑白人像摄影', '水彩人像插画', '3D 产品模型'];
(async () => {
    await assertOfflineValidation(origin);
    const browser = await chromium.launch({ headless: true });
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
        await context.addInitScript(({ origin, sourceIds }) => localStorage.setItem('infinite-canvas:prompt_source_store_v2', JSON.stringify({ state: { sources: [...sourceIds.map(id => ({ id, enabled: false, builtIn: true })), { id: 'sidebar-tag-fixture', name: '标签验收', url: origin + '/sidebar-tag-fixture.json', homepage: '', enabled: true, builtIn: false }], schedule: { intervalMinutes: 0 } }, version: 0 })), { origin, sourceIds });
        const page = await context.newPage();
        const errors = [], posts = [];
        page.on('pageerror', error => errors.push(error.message));
        page.on('console', message => { if (message.type() === 'error' && /Maximum update depth|Minified React error/.test(message.text())) errors.push(message.text()); });
        page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()); });
        await page.route('**/sidebar-tag-fixture.json', route => route.fulfill({ json: titles.map((title, index) => ({ id: 'tag-fixture-' + index, title, prompt: title + '：保留分段。\n\n使用柔和光线。', tags: [], coverUrl: '', referenceImageUrls: [] })) }));
        await page.goto(origin + '/infinite/canvas');
        await page.getByRole('button', { name: '新建画布', exact: true }).first().click();
        await page.waitForURL('**/infinite/canvas/*');
        await page.locator('aside').getByRole('button', { name: '提示词库', exact: true }).click();
        const sidebar = page.locator('[data-canvas-prompt-library]');
        const rows = sidebar.locator('[data-prompt-id]');
        const category = sidebar.getByRole('combobox', { name: '提示词用途', exact: true });
        const tags = sidebar.getByRole('group', { name: '提示词标签', exact: true });
        let activeDropdown;
        const dropdown = () => activeDropdown;
        const openSelect = async input => { await input.click(); const id = await input.getAttribute('aria-controls'); activeDropdown = page.locator('.ant-select-dropdown').filter({ has: page.locator(`[id="${id}"]`) }); };
        const waitCount = async count => {
            await page.waitForFunction(({ count }) => document.querySelectorAll('[data-canvas-prompt-library] [data-prompt-id]').length === count, { count });
        };
        const chooseCategory = async name => { await openSelect(category); await dropdown().locator('.ant-select-item-option-content').filter({ hasText: new RegExp('^' + name + '$') }).click(); await dropdown().waitFor({ state: 'hidden' }); };
        const chooseTag = name => tags.getByRole('button', { name, exact: true }).click();
        await waitCount(4);
        await chooseCategory('人像与写真');
        await waitCount(3);
        const options = await tags.getByRole('button').allTextContents();
        assert(options.includes('胶片') && options.includes('黑白') && options.includes('水彩'));
        assert(!options.includes('3D 渲染'));
        await chooseTag('胶片');
        await waitCount(1);
        assert((await rows.innerText()).includes('胶片人像摄影'));
        await chooseTag('黑白');
        await waitCount(2);
        assert.equal(await tags.getByRole('button', { name: '胶片', exact: true }).getAttribute('aria-pressed'), 'true');
        assert.equal(await tags.getByRole('button', { name: '黑白', exact: true }).getAttribute('aria-pressed'), 'true');
        assert(!(await rows.allTextContents()).some(text => text.includes('水彩')));
        await page.screenshot({ path: output + '/sidebar-tags-desktop.png' });
        await sidebar.getByPlaceholder('搜索主题、中文或原文').fill('黑白');
        await waitCount(1);
        assert((await rows.innerText()).includes('黑白人像摄影'));
        await sidebar.getByPlaceholder('搜索主题、中文或原文').fill('');
        await waitCount(2);
        await chooseCategory('产品与电商');
        await waitCount(1);
        assert.equal(await tags.getByRole('button', { name: '全部', exact: true }).getAttribute('aria-pressed'), 'true');
        assert.deepEqual(await tags.getByRole('button').allTextContents(), ['全部', '3D 渲染']);
        await chooseTag('3D 渲染');
        await waitCount(1);
        await chooseTag('3D 渲染');
        assert.equal(await tags.getByRole('button', { name: '3D 渲染', exact: true }).getAttribute('aria-pressed'), 'false');
        await chooseTag('3D 渲染');
        await chooseTag('全部');
        assert.equal(await tags.getByRole('button', { name: '全部', exact: true }).getAttribute('aria-pressed'), 'true');
        await chooseCategory('全部用途');
        await waitCount(4);
        await chooseTag('胶片');
        await chooseTag('黑白');
        await waitCount(2);
        await page.setViewportSize({ width: 390, height: 844 });
        await sidebar.waitFor({ state: 'visible' });
        assert(await sidebar.evaluate(element => element.scrollWidth <= element.clientWidth + 1));
        await page.screenshot({ path: output + '/sidebar-tags-mobile.png' });
        await page.reload();
        await page.locator('aside').getByRole('button', { name: '提示词库', exact: true }).click();
        await waitCount(4);
        assert.equal(await tags.getByRole('button', { name: '全部', exact: true }).getAttribute('aria-pressed'), 'true');
        assert.deepEqual(errors, []);
        assert.deepEqual(posts, []);
        const result = { inlineTagButtons: true, toggleOff: true, categoryScopedTags: true, multiSelectOrMatching: true, keywordIntersection: true, categoryChangeResetsTags: true, clearTags: true, allCategories: true, mobileFitsSidebar: true, reloadResetsFilters: true, browserErrors: errors, postRequests: posts };
        fs.writeFileSync(output + '/sidebar-tags-result.json', JSON.stringify(result, null, 2));
        console.log(JSON.stringify(result));
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });

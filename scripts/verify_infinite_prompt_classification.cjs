// Browser-local classification corrections must survive source refresh and apply across prompt surfaces.
const { chromium } = require('../canvas/node_modules/playwright');
const { assertOfflineValidation } = require('./infinite_test_environment.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const origin = process.env.INFINITE_TEST_URL || 'http://127.0.0.1:8772';
const output = 'data/infinite-validation';
const title = '分类校正人像摄影';
const body = 'A cinematic portrait with soft light.\n\nKeep the exact word "EXAMPLE".';
const translated = '柔光电影人像。\n\n保留文字“EXAMPLE”。';
const builtIns = ['prompt-portal', 'banana-prompt-quicker', 'davidwu-gpt-image2-prompts', 'freestylefly-gpt-image-2', 'awesome-gpt-image', 'awesome-gpt4o-image-prompts', 'youmind-gpt-image-2', 'youmind-nano-banana-pro'];
(async () => {
    await assertOfflineValidation(origin);
    const browser = await chromium.launch({ headless: true });
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
        await context.addInitScript(({ origin, builtIns }) => {
            if (!localStorage.getItem('infinite-canvas:prompt_source_store_v2')) localStorage.setItem('infinite-canvas:prompt_source_store_v2', JSON.stringify({ state: { sources: [...builtIns.map(id => ({ id, builtIn: true, enabled: false })), ...['a', 'b'].map(id => ({ id: 'correction-' + id, name: '校正验收 ' + id, url: origin + '/correction-' + id + '.json', homepage: 'https://example.com/' + id, enabled: true, builtIn: false }))], schedule: { intervalMinutes: 0 } }, version: 0 }));
        }, { origin, builtIns });
        const page = await context.newPage();
        const errors = [], posts = [];
        page.on('pageerror', error => errors.push(error.message));
        page.on('console', message => { if (message.type() === 'error' && /Maximum update depth|Minified React error/.test(message.text())) errors.push(message.text()); });
        page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()); });
        let refreshed = false;
        await page.route('**/correction-a.json', route => route.fulfill({ json: [{ id: 'original', title, prompt: body, promptZh: translated, tags: refreshed ? ['3D', '@WrongAuthor'] : ['Photography'], referenceImageUrls: [] }, { id: 'product', title: '3D 产品模型', prompt: 'Unrelated product example.', tags: [] }] }));
        await page.route('**/correction-b.json', route => route.fulfill({ json: [{ id: 'translated', title: '镜像人像案例', prompt: translated, tags: ['Realistic'], referenceImageUrls: [] }] }));
        const editor = () => page.getByRole('dialog', { name: '修改分类与标签', exact: true });
        const detail = () => page.getByRole('dialog', { name: title, exact: true });
        const openEditor = async () => { await detail().getByRole('button', { name: '修改分类与标签', exact: true }).click(); await editor().waitFor(); };
        const save = async () => { await editor().getByRole('button', { name: /^保\s*存$/ }).click(); await editor().waitFor({ state: 'hidden' }); };
        const choose = async (input, name) => { await input.click(); const id = await input.getAttribute('aria-controls'); const popup = page.locator('.ant-select-dropdown').filter({ has: page.locator(`[id="${id}"]`) }); await popup.locator('.ant-select-item-option-content').filter({ hasText: new RegExp('^' + name + '$') }).click(); await popup.waitFor({ state: 'hidden' }); };
        await page.goto(origin + '/infinite/prompts');
        await page.getByRole('heading', { name: title, exact: true }).click();
        assert.equal(await detail().locator('pre').textContent(), translated);
        await openEditor();
        const tagButtons = () => editor().getByRole('group', { name: '编辑提示词标签', exact: true });
        await tagButtons().getByRole('button', { name: '写实摄影', exact: true }).click();
        await editor().getByRole('button', { name: /^取\s*消$/ }).click();
        await detail().getByText('写实摄影', { exact: true }).waitFor();
        await openEditor();
        await choose(editor().getByRole('combobox', { name: '提示词分类', exact: true }), '插画与艺术');
        await tagButtons().getByRole('button', { name: '写实摄影', exact: true }).click();
        await tagButtons().getByRole('button', { name: '水彩', exact: true }).click();
        await editor().getByRole('textbox', { name: '自定义标签', exact: true }).fill('我的风格');
        await page.keyboard.press('Enter');
        await page.screenshot({ path: output + '/prompt-classification-editor-desktop.png', animations: 'disabled' });
        await save();
        await detail().getByText('已校正', { exact: true }).waitFor();
        await detail().getByText('我的风格', { exact: true }).waitFor();
        assert.equal(await detail().getByText('写实摄影', { exact: true }).count(), 0);
        assert.equal(await detail().locator('pre').textContent(), translated);
        await detail().getByText('原始提示词', { exact: true }).click();
        assert.equal(await detail().locator('pre').textContent(), body);
        await page.keyboard.press('Escape');
        await page.reload();
        const card = page.locator('.ant-card').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
        await card.getByText('我的风格', { exact: true }).waitFor();
        assert((await card.innerText()).includes('插画与艺术'));
        assert.equal(await page.getByRole('heading', { name: '镜像人像案例', exact: true }).count(), 0);
        // Clear only the public source cache to force a fresh source read; keep correction storage intact.
        refreshed = true;
        await page.evaluate(() => new Promise((resolve, reject) => { const r = indexedDB.open('infinite-canvas'); r.onsuccess = () => { const db = r.result, tx = db.transaction('prompt_cache', 'readwrite'); tx.objectStore('prompt_cache').clear(); tx.oncomplete = () => { db.close(); resolve(); }; tx.onerror = () => reject(tx.error); }; }));
        await page.reload();
        await card.getByText('我的风格', { exact: true }).waitFor();
        assert((await card.innerText()).includes('插画与艺术'));
        await page.goto(origin + '/infinite/canvas');
        await page.getByRole('button', { name: '新建画布', exact: true }).first().click();
        await page.waitForURL('**/infinite/canvas/*');
        await page.locator('aside').getByRole('button', { name: '提示词库', exact: true }).click();
        const sidebar = page.locator('[data-canvas-prompt-library]');
        await sidebar.getByPlaceholder('搜索主题、中文或原文').fill(title);
        await sidebar.locator('[data-prompt-id]').filter({ hasText: title }).waitFor();
        await choose(sidebar.getByRole('combobox', { name: '提示词用途', exact: true }), '插画与艺术');
        await sidebar.getByRole('group', { name: '提示词标签', exact: true }).getByRole('button', { name: '我的风格', exact: true }).click();
        await sidebar.locator('[data-prompt-id]').filter({ hasText: title }).waitFor();
        assert.equal(await sidebar.locator('[data-prompt-id]').count(), 1);
        await sidebar.getByRole('button', { name: '查看详情', exact: true }).click();
        await openEditor();
        await page.setViewportSize({ width: 390, height: 844 });
        assert(await editor().evaluate(element => element.scrollWidth <= element.clientWidth + 1));
        await page.screenshot({ path: output + '/prompt-classification-editor-mobile.png', animations: 'disabled' });
        await editor().getByRole('button', { name: /^取\s*消$/ }).click();
        await page.keyboard.press('Escape');
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.goto(origin + '/infinite/image');
        await page.getByRole('button', { name: '查看提示词库', exact: true }).click();
        const picker = page.getByRole('dialog', { name: '提示词库', exact: true });
        await picker.getByPlaceholder('搜索主题、中文描述或原文').fill('我的风格');
        await picker.getByRole('heading', { name: title, exact: true }).click();
        await detail().getByText('我的风格', { exact: true }).waitFor();
        await openEditor();
        await editor().getByRole('button', { name: '恢复自动分类', exact: true }).click();
        await editor().waitFor({ state: 'hidden' });
        await detail().getByText('写实摄影', { exact: true }).waitFor();
        assert.equal(await detail().getByText('已校正', { exact: true }).count(), 0);
        assert.equal(await detail().getByText('我的风格', { exact: true }).count(), 0);
        await page.keyboard.press('Escape');
        await page.keyboard.press('Escape');
        await page.goto(origin + '/infinite/prompts');
        await card.getByText('写实摄影', { exact: true }).waitFor();
        assert(!(await card.innerText()).includes('我的风格'));
        assert.deepEqual(errors, []);
        assert.deepEqual(posts, []);
        const result = { editTopicAndTags: true, customTag: true, cancelPreserves: true, originalsPreserved: true, dedupPreserved: true, reloadPersists: true, sourceRefreshPreserves: true, sidebarFilters: true, pickerSharesCorrection: true, restoreAutomatic: true, mobileLayout: true, browserErrors: errors, postRequests: posts };
        fs.writeFileSync(output + '/prompt-classification-result.json', JSON.stringify(result, null, 2));
        console.log(JSON.stringify(result));
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
